class FakeParticipants:
    """No client process exists in this experiment; confirmations are fake."""
    def pause(self, _handles): return True
    def resume(self, _handles): return True


def install_probe(case, port, lease, epoch, *, marker_required=False):
    """Install into a disposable case generated by snapshot.prepare_case only."""
    reuse.install_probe(case, port, lease, epoch)
    lab = case/'extensions/x4_lan_lab'
    ui = lab/'ui'
    (ui/'authority_reuse_probe.lua').unlink()
    import shutil
    for source, target in ((ROOT/'src/authority/lua/local_control_bridge.lua', 'local_control_bridge.lua'),
                           (ROOT/'tools/dev/authority_world_bridge_probe.lua', 'authority_world_bridge_probe.lua')):
        shutil.copyfile(source, ui/target)
    if marker_required:
        shutil.copyfile(ROOT/'src/authority/md/checkpoint_marker.xml', lab/'md/authority_checkpoint_marker.xml')
    files = [*extension.BASE_UI, 'ui/x4ls_autostart.lua', 'ui/authority_control_state.lua',
             'ui/x4_control_engine.lua', 'ui/local_control_bridge.lua', 'ui/authority_world_bridge_probe.lua']
    (lab/'ui.xml').write_text(extension.ui_xml(files), encoding='utf-8')
    (ui/'config.lua').write_text('X4LAN_CONFIG = {enabled=false, test_profile="45841", '
        'x4ls_autostart="custom_creative", authority_world_bridge=true, '
        f'authority_control_port={port}, authority_control_lease="{lease}", authority_world_epoch="{epoch}", '
        f'authority_marker_required={str(marker_required).lower()}'+'}\n', encoding='ascii')


def execute_world(world, store, *, expect_markers=False):
    """Join twice and save after last departure; client loads are deliberate fakes."""
    def step(operation):
        if world.session.pending is None or world.session.pending.operation != operation:
            raise RuntimeError('unexpected world operation')
        world.step()
    def fake_load(handle):
        offer = world.offer_load(handle)
        world.mark_loaded(offer.world_epoch, handle, offer.baseline_id, offer.load_generation,
                          offer.save.checkpoint_id, offer.save.sha256, trusted_confirmation=True)
        return {'checkpoint_id': offer.save.checkpoint_id, 'sha256': offer.save.sha256,
                'load_confirmation': 'FAKE; no download or X4 load'}
    first = world.join('fake-client-a')
    step('pause'); step('save')
    a = fake_load(first); step('resume')
    second = world.join('fake-client-b')
    step('pause'); step('save')
    b = fake_load(second); step('resume')
    if world.session.state != 'running' or a['checkpoint_id'] == b['checkpoint_id']:
        raise RuntimeError('world lifecycle did not complete')
    world.disconnect(first)
    if world.session.state != 'running':
        raise RuntimeError('world stopped while a ready client remained')
    world.disconnect(second)
    step('pause'); step('save')
    last = store.latest()
    if expect_markers:
        checkpoints = [store.get(a['checkpoint_id']), store.get(b['checkpoint_id']), last]
        if len({c.marker for c in checkpoints}) != len(checkpoints) or any(c.marker is None for c in checkpoints):
            raise RuntimeError('missing or repeated save marker')
        # The bridge checked each save's typed MD reference and false load flag
        # before native confirmation; these immutable generations have been
        # revalidated by the store above. Raw marker-text searches add no proof.
        if store.latest_marked_confirmed() != last:
            raise RuntimeError('marked last-departure checkpoint was not confirmed')
    if (world.session.state != 'paused' or world.session.players or
            last.checkpoint_id in {a['checkpoint_id'], b['checkpoint_id']}):
        raise RuntimeError('last departure did not leave a new paused checkpoint')
    return {'fake_client_loads': [a, b], 'last_departure_checkpoint': {
        'checkpoint_id': last.checkpoint_id, 'sha256': last.sha256}, 'final_state': 'paused'}


def run(args):
    if sys.platform != 'linux' or os.geteuid() == 0:
        raise ValueError('run as unprivileged Linux Steam desktop user')
    out = snapshot.output_path(args.out)
    game = args.game.resolve(strict=True)
    import shutil
    if live.sha(game/'X4') != live.EXE_SHA or not (game/'extensions').is_dir() or not shutil.which('bwrap'):
        raise ValueError('pinned game or bubblewrap unavailable')
    if live.x4_executables(): raise ValueError('another X4 process is running')
    if not re.fullmatch(r':[0-9]+(?:\.[0-9]+)?',args.display): raise ValueError('local X11 display required')
    auth = Path(os.environ.get('XAUTHORITY',''))
    if not auth.is_file() or not os.access(auth,os.R_OK): raise ValueError('readable XAUTHORITY required')
    auth = auth.resolve(strict=True)
    if args.timeout <= 0 or not 0 <= args.seed <= 0xffffffff: raise ValueError('invalid timeout or seed')
    user = pwd.getpwuid(os.geteuid()); home = Path(user.pw_dir)
    steam = live.steam_identity(home,user.pw_uid)
    out.mkdir(mode=0o700,parents=True,exist_ok=False)
    result={'success':False, 'scope':'one isolated Linux X4; two FAKE client load confirmations and last departure; no multiplayer'}
    proc=started=lock_fd=lock_stat=service=None
    handlers={};sock=socket.socket(socket.AF_INET,socket.SOCK_DGRAM)
    try:
        sock.bind(('127.0.0.1',0));sock.settimeout(.25)
        lease=secrets.token_hex(16);epoch=secrets.token_hex(16)
        case,profile,binds,lock=snapshot.prepare_case(out,game,home)
        if any(p.name!='steam_autocloud.vdf' for p in (profile/'save').iterdir()):
            raise RuntimeError('new isolated save directory is not empty')
        marker_required=getattr(args,'marker_required',False)
        install_probe(case,sock.getsockname()[1],lease,epoch,marker_required=marker_required)
        (out/'checkpoints').mkdir(mode=0o700)
        store=CheckpointStore(out/'checkpoints')
        lock_fd,lock_stat=live.create_lock_target(snapshot.LOCK_TARGET,user.pw_uid,user.pw_gid)
        for number in (signal.SIGTERM,signal.SIGINT,signal.SIGHUP):
            handlers[number]=signal.signal(number,snapshot.cancel_capture)
        with (out/'process.log').open('wb') as log:
            proc=subprocess.Popen(snapshot.command_for(case,game,binds,lock,args.display,auth,user.pw_name,args.seed),
                                  stdin=subprocess.DEVNULL,stdout=log,stderr=subprocess.STDOUT,start_new_session=True)
            started=live.start_ticks(proc.pid)
            deadline=time.monotonic()+args.timeout
            peer=None
            while peer is None:
                if time.monotonic() >= deadline: raise TimeoutError('bridge enrollment timed out')
                if proc.poll() is not None: raise RuntimeError('isolated X4 exited before enrollment')
                if live.steam_identity(home,user.pw_uid)!=steam: raise RuntimeError('Steam identity changed')
                try: data,address=sock.recvfrom(769)
                except socket.timeout: continue
                if data==f'HELLO|{lease}|{epoch}'.encode('ascii') and address[0]=='127.0.0.1': peer=address
            adapter=LocalControlBridge(enabled=True,sock=sock,peer=peer,lease=lease,world_epoch=epoch,
                profile=profile,store=store,verify_checkpoint=read_cycle_evidence,timeout=min(130,args.timeout),
                marker_required=marker_required)
            service=joinfiles.FileService(secrets.token_hex(16),slots=(1,2)).start()
            world=WorldCoordinator(epoch,adapter,store,SaveOffers(service,store),participants=FakeParticipants())
            result['lifecycle']=execute_world(world,store,expect_markers=marker_required)
            result['marked_saves_checked']=marker_required
            if proc.poll() is not None or live.steam_identity(home,user.pw_uid)!=steam:
                raise RuntimeError('owned X4 or Steam identity changed during lifecycle')
            result['success']=True
    except (Exception,KeyboardInterrupt) as error:
        result['error']=str(error)
    finally:
        if service is not None: service.close()
        sock.close()
        if proc is not None and started is None and proc.poll() is None:
            try: proc.terminate();proc.wait(timeout=15)
            except (OSError,subprocess.TimeoutExpired): result.update(success=False,cleanup_error='launcher cleanup failed')
        if started is not None:
            try:
                remaining=snapshot.stop_owned(proc,started)
                result['owned_processes_remaining']=remaining
                if remaining: result.update(success=False,cleanup_error='owned process group remains')
            except (OSError,subprocess.TimeoutExpired): result.update(success=False,cleanup_error='owned process cleanup failed')
        if lock_stat is not None:
            try: live.release_lock_target(snapshot.LOCK_TARGET,lock_fd,lock_stat)
            except (OSError,RuntimeError): result.update(success=False,cleanup_error='lock cleanup failed')
        for number,handler in handlers.items(): signal.signal(number,handler)
        try:
            if live.steam_identity(home,user.pw_uid)!=steam: result.update(success=False,error='Steam identity changed')
        except (OSError,ValueError,RuntimeError): result.update(success=False,error='Steam identity unavailable')
        config=out/'case/extensions/x4_lan_lab/ui/config.lua'
        if config.is_file():
            try:
                text=config.read_text(encoding='ascii')
                redacted,count=re.subn(r'authority_control_lease="[0-9a-f]{32}"','authority_control_lease="redacted"',text)
                if count!=1: raise ValueError('invalid lease configuration')
                config.write_text(redacted,encoding='ascii')
            except (OSError,UnicodeError,ValueError): result.update(success=False,cleanup_error='lease cleanup failed')
        (out/'result.json').write_text(json.dumps(result,indent=2)+'\n')
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--game',required=True,type=Path);p.add_argument('--out',required=True,type=Path)
    p.add_argument('--display',required=True);p.add_argument('--timeout',type=float,default=600)
    p.add_argument('--seed',type=int,default=276944566)
    p.add_argument('--marker-required',action='store_true',help='experimental repeated save marker check')
    try: result=run(p.parse_args())
    except (OSError,ValueError,RuntimeError) as error: p.exit(1,'REFUSED: '+str(error)+'\n')
    print(json.dumps(result,indent=2));return 0 if result['success'] else 1

if __name__=='__main__': sys.exit(main())
